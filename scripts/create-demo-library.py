#!/usr/bin/env python3
"""Generate a small, explicitly synthetic music collection for Macarok testing."""

from __future__ import annotations

import argparse
import array
import json
import math
from pathlib import Path
import shutil
import struct
import subprocess
import sys
import wave
import zlib


MARKER = ".macarok-demo.json"
SAMPLE_RATE = 44_100


def png_artwork(path: Path, seed: int) -> None:
    """Write a tiny RGB PNG using only the standard library."""
    size = 160
    palettes = [(33, 92, 107), (173, 100, 67), (88, 105, 76), (105, 87, 133)]
    base = palettes[seed % len(palettes)]
    rows = bytearray()
    for y in range(size):
        rows.append(0)
        for x in range(size):
            distance = math.hypot(x - size * 0.63, y - size * 0.38)
            ring = 48 < distance < 56
            light = (x + y) / (size * 2)
            rows.extend(min(255, int(channel * (0.65 + light * 0.65) + (75 if ring else 0))) for channel in base)

    def chunk(kind: bytes, value: bytes) -> bytes:
        return struct.pack(">I", len(value)) + kind + value + struct.pack(">I", zlib.crc32(kind + value) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(bytes(rows), 9))
    png += chunk(b"IEND", b"")
    path.write_bytes(png)


def write_wave(path: Path, duration: float, metadata: dict[str, str], audible: bool, frequency: float) -> None:
    frames = int(duration * SAMPLE_RATE)
    samples = array.array("h")
    for index in range(frames):
        if audible:
            edge = min(1.0, index / 441, (frames - index) / 441)
            sample = int(350 * edge * math.sin(2 * math.pi * frequency * index / SAMPLE_RATE))
        else:
            sample = 0
        samples.extend((sample, sample))
    if sys.byteorder != "little":
        samples.byteswap()
    with wave.open(str(path), "wb") as output:
        output.setnchannels(2)
        output.setsampwidth(2)
        output.setframerate(SAMPLE_RATE)
        output.writeframes(samples.tobytes())

    # RIFF INFO is readable by TagLib; the PCM payload remains untouched.
    identifiers = {"title": b"INAM", "artist": b"IART", "album": b"IPRD", "date": b"ICRD", "genre": b"IGNR", "track": b"ITRK"}
    info = bytearray(b"INFO")
    for key, identifier in identifiers.items():
        if key not in metadata:
            continue
        text = metadata[key].encode("utf-8") + b"\0"
        info.extend(identifier + struct.pack("<I", len(text)) + text)
        if len(text) % 2:
            info.append(0)
    with path.open("r+b") as output:
        output.seek(0, 2)
        output.write(b"LIST" + struct.pack("<I", len(info)) + info)
        size = output.tell()
        output.seek(4)
        output.write(struct.pack("<I", size - 8))


def convert(ffmpeg: str, source: Path, destination: Path, metadata: dict[str, str], codec: list[str]) -> tuple[bool, str]:
    command = [ffmpeg, "-hide_banner", "-loglevel", "error", "-nostdin", "-y", "-i", str(source), "-vn", *codec]
    for key, value in metadata.items():
        command.extend(["-metadata", f"{key}={value}"])
    command.append(str(destination))
    try:
        result = subprocess.run(command, capture_output=True, text=True, timeout=60, check=False)
    except (OSError, subprocess.TimeoutExpired) as error:
        return False, str(error)
    if result.returncode:
        destination.unlink(missing_ok=True)
        return False, result.stderr.strip().splitlines()[-1] if result.stderr.strip() else "Encoder failed."
    return True, ""


def clean_generated_files(destination: Path) -> None:
    marker = destination / MARKER
    if not marker.is_file():
        raise ValueError("--force only resets a library previously generated by this script.")
    manifest = json.loads(marker.read_text())
    for relative in manifest.get("generated_files", []):
        path = destination / relative
        if path.resolve().is_relative_to(destination.resolve()) and path.is_file():
            path.unlink()
    marker.unlink()
    for folder in sorted((path for path in destination.rglob("*") if path.is_dir()), key=lambda path: len(path.parts), reverse=True):
        try:
            folder.rmdir()
        except OSError:
            pass


def create_library(destination: Path, audible: bool, codecs: bool) -> dict:
    destination.mkdir(parents=True, exist_ok=True)
    generated: list[Path] = []
    normal_tracks: list[Path] = []
    albums = [
        ("Meridian Atlas", "Afterlight", "2005", "Ambient", ["First Light", "Quiet Streets", "The Long Way Home"]),
        ("Paper Satellites", "Field Notes", "2013", "Electronic", ["Small Signals", "Open Windows", "Night Geometry"]),
    ]
    for album_index, (artist, album, year, genre, titles) in enumerate(albums):
        folder = destination / artist / f"{year} - {album}"
        folder.mkdir(parents=True, exist_ok=True)
        for index, title in enumerate(titles, 1):
            path = folder / f"{index:02d} - {title}.wav"
            metadata = {"title": title, "artist": artist, "album": album, "album_artist": artist, "date": year, "genre": genre, "track": str(index)}
            write_wave(path, 4 + index, metadata, audible, 170 + album_index * 70 + index * 30)
            generated.append(path)
            normal_tracks.append(path)
        image = folder / "cover.png"
        png_artwork(image, album_index)
        generated.append(image)

    ffmpeg = shutil.which("ffmpeg") if codecs else None
    encoded_formats: list[str] = []
    skipped_formats: dict[str, str] = {}
    cue_folder = destination / "North Window" / "2026 - Continuous Album"
    cue_folder.mkdir(parents=True, exist_ok=True)
    cue_audio = cue_folder / "album.wav"
    cue_metadata = {"title": "Continuous Album", "artist": "North Window", "album_artist": "North Window", "album": "Continuous Album", "date": "2026", "genre": "Instrumental"}
    write_wave(cue_audio, 12, cue_metadata, audible, 220)
    if ffmpeg:
        flac = cue_audio.with_suffix(".flac")
        success, error = convert(ffmpeg, cue_audio, flac, cue_metadata, ["-c:a", "flac"])
        if success:
            cue_audio.unlink()
            cue_audio = flac
        else:
            skipped_formats["cue-flac"] = error
    generated.append(cue_audio)
    cue = cue_folder / "album.cue"
    cue.write_text(f'''REM DATE 2026
REM GENRE Instrumental
PERFORMER "North Window"
TITLE "Continuous Album"
FILE "{cue_audio.name}" WAVE
  TRACK 01 AUDIO
    TITLE "First Window"
    INDEX 01 00:00:00
  TRACK 02 AUDIO
    TITLE "Second Window"
    INDEX 00 00:03:50
    INDEX 01 00:04:00
  TRACK 03 AUDIO
    TITLE "Third Window"
    INDEX 01 00:08:00
''', encoding="utf-8")
    generated.append(cue)
    image = cue_folder / "cover.png"
    png_artwork(image, 2)
    generated.append(image)

    if ffmpeg:
        folder = destination / "Macarok Demo" / "2026 - Codec Checks"
        folder.mkdir(parents=True, exist_ok=True)
        formats = [
            ("MP3", "mp3", ["-c:a", "libmp3lame", "-b:a", "192k"]),
            ("FLAC", "flac", ["-c:a", "flac"]),
            ("Ogg Vorbis", "ogg", ["-c:a", "libvorbis", "-q:a", "5"]),
            ("Ogg Opus", "opus", ["-c:a", "libopus", "-b:a", "128k"]),
        ]
        for index, (name, extension, codec) in enumerate(formats, 1):
            path = folder / f"{index:02d} - {name}.{extension}"
            metadata = {"title": name, "artist": "Macarok Demo", "album_artist": "Macarok Demo", "album": "Codec Checks", "date": "2026", "genre": "Test Audio", "track": str(index)}
            success, error = convert(ffmpeg, normal_tracks[0], path, metadata, codec)
            if not success and name == "Ogg Vorbis":
                # Some macOS ffmpeg distributions ship the native encoder but not libvorbis.
                success, error = convert(ffmpeg, normal_tracks[0], path, metadata, ["-c:a", "vorbis", "-strict", "-2", "-q:a", "5"])
            if success:
                generated.append(path)
                normal_tracks.append(path)
                encoded_formats.append(name)
            else:
                skipped_formats[name] = error
        image = folder / "cover.png"
        png_artwork(image, 3)
        generated.append(image)

    def relative(path: Path) -> str:
        return path.relative_to(destination).as_posix()

    m3u = destination / "Demo Playlist.m3u8"
    lines = ["#EXTM3U"]
    for path in normal_tracks[:3]:
        lines += [f"#EXTINF:-1,{path.stem}", relative(path)]
    for index, title in enumerate(["First Window", "Second Window", "Third Window"]):
        lines += [f"#EXTINF:4,North Window - {title}", f"#EXTVLCOPT:start-time={index * 4}", f"#EXTVLCOPT:stop-time={(index + 1) * 4}", relative(cue_audio)]
    m3u.write_text("\n".join(lines) + "\n", encoding="utf-8")
    generated.append(m3u)
    pls = destination / "Demo Playlist.pls"
    pls_lines = ["[playlist]", "NumberOfEntries=2"]
    for index, path in enumerate(normal_tracks[:2], 1):
        pls_lines += [f"File{index}={relative(path)}", f"Title{index}={path.stem}", f"Length{index}=-1"]
    pls_lines += ["Version=2"]
    pls.write_text("\n".join(pls_lines) + "\n", encoding="utf-8")
    generated.append(pls)
    readme = destination / "README.txt"
    readme.write_text("Macarok Demo Library\n\nThis collection is synthetic test data generated locally.\n" + ("Tracks contain quiet test tones.\n" if audible else "Tracks contain silence so automated playback checks remain quiet.\n") + "\nUse album.cue to verify three logical tracks backed by one audio file.\nThe M3U playlist includes those segment boundaries; the PLS playlist uses whole files.\n", encoding="utf-8")
    generated.append(readme)
    manifest = {"name": "Macarok Demo", "audible": audible, "sample_rate": SAMPLE_RATE,
                "cue_audio": relative(cue_audio), "encoded_formats": encoded_formats,
                "skipped_formats": skipped_formats, "ffmpeg_available": ffmpeg is not None,
                "expected_tracks": 9 + len(encoded_formats),
                "generated_files": [relative(path) for path in generated]}
    (destination / MARKER).write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("destination", nargs="?", type=Path, default=Path(".build/demo-library"))
    parser.add_argument("--audible", action="store_true", help="Generate quiet tones instead of silence.")
    parser.add_argument("--no-codecs", action="store_true", help="Use only the standard library, without optional ffmpeg conversions.")
    parser.add_argument("--force", action="store_true", help="Reset only files recorded by an earlier run of this script.")
    args = parser.parse_args()
    destination = args.destination.expanduser().resolve()
    if destination.exists() and any(destination.iterdir()):
        if not args.force:
            parser.error("The destination is not empty. Choose another directory or use --force for an existing Macarok demo.")
        try:
            clean_generated_files(destination)
        except (ValueError, OSError, json.JSONDecodeError) as error:
            parser.error(str(error))
    manifest = create_library(destination, args.audible, not args.no_codecs)
    print(destination)
    print(f"Expected library tracks: {manifest['expected_tracks']} (including three CUE tracks)")
    print("Audio: " + ("quiet tones" if args.audible else "silence"))
    print("Extra codecs: " + (", ".join(manifest["encoded_formats"]) or "not generated; ffmpeg is optional"))
    for name, error in manifest["skipped_formats"].items():
        print(f"Skipped {name}: {error}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
